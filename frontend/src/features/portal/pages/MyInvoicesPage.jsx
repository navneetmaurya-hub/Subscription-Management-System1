import React, { useEffect, useState } from 'react';
import { invoicesApi } from '../../../api/invoices.api';
import { formatCurrency } from '../../../utils/formatCurrency';
import { formatDate } from '../../../utils/formatDate';
import Card from '../../../components/ui/Card';
import StatusBadge from '../../../components/common/StatusBadge';
import Table from '../../../components/ui/Table';
import Spinner from '../../../components/ui/Spinner';
import EmptyState from '../../../components/ui/EmptyState';
import { Receipt } from 'lucide-react';

export default function MyInvoicesPage() {
    const [invoices, setInvoices] = useState([]);
    const [loading, setLoading] = useState(true);

    useEffect(() => {
        invoicesApi.getAll()
            .then((res) => setInvoices(res.data || []))
            .catch(console.error)
            .finally(() => setLoading(false));
    }, []);

    const columns = [
        { header: 'Invoice #', accessor: 'number', cell: (row) => <span className="font-bold text-gray-900">{row.number}</span> },
        { header: 'Status', accessor: 'status', cell: (row) => <StatusBadge status={row.status} /> },
        { header: 'Due Date', accessor: 'dueDate', cell: (row) => formatDate(row.dueDate) },
        { header: 'Total', accessor: 'total', cell: (row) => <span className="font-bold text-gray-900">{formatCurrency(row.total)}</span> },
        { header: 'Paid', accessor: 'amountPaid', cell: (row) => <span className="text-emerald-600 font-semibold">{formatCurrency(row.amountPaid || 0)}</span> },
        {
            header: 'Balance',
            cell: (row) => (
                <span className={row.total - (row.amountPaid || 0) > 0 ? 'text-[#e04f2d] font-bold' : 'text-emerald-700'}>
                    {formatCurrency(row.total - (row.amountPaid || 0))}
                </span>
            ),
        },
    ];

    if (loading) return <Spinner size="lg" />;

    return (
        <div className="space-y-6">
            <div>
                <h1 className="text-2xl font-extrabold text-gray-900 tracking-tight">My Invoices</h1>
                <p className="text-xs text-gray-500 mt-1">View your billing history, tax invoices, and payment receipts.</p>
            </div>

            <Card>
                {invoices.length === 0 ? (
                    <EmptyState
                        icon={Receipt}
                        title="No invoices found"
                        description="Invoices will be available here once generated by the billing engine."
                    />
                ) : (
                    <Table columns={columns} data={invoices} />
                )}
            </Card>
        </div>
    );
}

